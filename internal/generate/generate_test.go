func newOptions(t *testing.T, template string) Options {
	return Options{
		Package:  "com.example.myapp",
		Project:  "MyApp",
		Template: template,
		OutDir:   t.TempDir(),
		NoGit:    true,
	}
}

func TestProjectTemplates(t *testing.T) {
	for _, template := range []string{"main", "single", "empty", "kmm"} {
		t.Run(template, func(t *testing.T) {
			opts := newOptions(t, template)
			if template == "kmm" {
				opts.TeamID = "ABCDE12345"
			}
			var stdout, stderr bytes.Buffer
			if err := Project(opts, &stdout, &stderr); err != nil {
				t.Fatalf("Project: %v\n%s", err, stderr.String())
			}

			root := filepath.Join(opts.OutDir, "MyApp")
			files := 0
			err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
				if err != nil {
					return err
				}
				rel, _ := filepath.Rel(root, p)
				if skippedNames[d.Name()] {
					t.Errorf("skipped path copied: %s", rel)
				}
				if strings.Contains(filepath.ToSlash(rel), "paulcoding") {
					t.Errorf("path not renamed: %s", rel)
				}
				if d.IsDir() {
					return nil
				}
				files++
				data, err := os.ReadFile(p)
				if err != nil {
					return err
				}
				lower := strings.ToLower(string(data))
				for _, old := range []string{"paulcoding", "androidtemplate", "android template", "android-template", "android_template"} {
					if strings.Contains(lower, old) {
						t.Errorf("template identifier %q left in %s", old, rel)
					}
				}
				return nil
			})
			if err != nil {
				t.Fatal(err)
			}
			if files == 0 {
				t.Fatal("no files generated")
			}

			settings, err := os.ReadFile(filepath.Join(root, "settings.gradle.kts"))
			if err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(string(settings), `rootProject.name = "MyApp"`) {
				t.Error("rootProject.name not set to project name")
			}

			props, err := os.ReadFile(filepath.Join(root, "gradle.properties"))
			if err != nil {
				t.Fatal(err)
			}
			if want := "# Generated by gen-android "; !strings.HasPrefix(string(props), want) || !strings.Contains(string(props), "("+template+" template)") {
				t.Errorf("gradle.properties missing generator header:\n%.120s", props)
			}

			if info, err := os.Stat(filepath.Join(root, "gradlew")); err != nil || info.Mode()&0100 == 0 {
				t.Errorf("gradlew missing or not executable: %v", err)
			}

			if template == "kmm" {
				cfg, err := os.ReadFile(filepath.Join(root, "iosApp", "Configuration", "Config.xcconfig"))
				if err != nil {
					t.Fatal(err)
				}
				if !strings.Contains(string(cfg), "TEAM_ID=ABCDE12345\n") {
					t.Error("team ID not written to Config.xcconfig")
				}
			}
		})
	}
}

func TestProjectMinSDK(t *testing.T) {
	for _, template := range []string{"main", "single", "empty", "kmm"} {
		t.Run(template, func(t *testing.T) {
			opts := newOptions(t, template)
			opts.MinSDK = 26
			var stdout, stderr bytes.Buffer
			if err := Project(opts, &stdout, &stderr); err != nil {
				t.Fatal(err)
			}
			root := filepath.Join(opts.OutDir, opts.Project)
			catalog, err := os.ReadFile(filepath.Join(root, "gradle", "libs.versions.toml"))
			if err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(string(catalog), `android-minSdk = "26"`) {
				t.Error("catalog minSdk not updated")
			}
			// Every module must read minSdk from the catalog, or --min-sdk would miss it.
			filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
				if err != nil || d.IsDir() || !strings.HasSuffix(p, ".gradle.kts") {
					return err
				}
				data, _ := os.ReadFile(p)
				for _, line := range strings.Split(string(data), "\n") {
					if strings.Contains(line, "minSdk =") && !strings.Contains(line, "libs.versions.android.minSdk") {
						t.Errorf("%s hardcodes minSdk: %s", p, strings.TrimSpace(line))
					}
				}
				return nil
			})
		})
	}
}

func TestProjectAppName(t *testing.T) {
	opts := newOptions(t, "kmm")
	opts.AppName = `Bob's "Notes" & $tuff`
	var stdout, stderr bytes.Buffer
	if err := Project(opts, &stdout, &stderr); err != nil {
		t.Fatal(err)
	}
	root := filepath.Join(opts.OutDir, opts.Project)
	for file, want := range map[string]string{
		"androidApp/src/main/res/values/strings.xml":                             `<string name="app_name">Bob\'s \"Notes\" &amp; $tuff</string>`,
		"iosApp/iosApp/Info.plist":                                               `<string>Bob's "Notes" &amp; $tuff</string>`,
		"jvmApp/src/main/kotlin/com/example/myapp/jvm/Main.kt":                   `title = "Bob's \"Notes\" & \$tuff",`,
		"iosApp/Configuration/Config.xcconfig":                                   "PRODUCT_NAME=MyApp",
		"shared/src/commonMain/kotlin/com/example/myapp/data/DatabaseFactory.kt": `"myapp.db"`,
	} {
		data, err := os.ReadFile(filepath.Join(root, file))
		if err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(string(data), want) {
			t.Errorf("%s: want %s\n%s", file, want, data)
		}
	}
}

